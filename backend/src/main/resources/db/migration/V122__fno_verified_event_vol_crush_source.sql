-- STR-202 EMPTY event-anchored NIFTY IV crush research custody; retrospective ONLY.
-- Source-verified official event schedule was known before the event.
-- Original pre/post normalized 30d ATM IV AND NIFTY spot, no reconstructed trade.
CREATE TABLE fno_nifty_vol_crush_event_source (
 evidence_id BIGSERIAL PRIMARY KEY,
 provider_code VARCHAR(32) NOT NULL CHECK(provider_code IN ('UPSTOX_ANALYTICS','ANGEL_ONE_SMARTAPI')),
 index_key VARCHAR(80) NOT NULL CHECK(index_key='NSE_INDEX|Nifty 50'),
 event_key VARCHAR(80) NOT NULL UNIQUE CHECK(event_key ~ '^[A-Za-z0-9._:-]{3,80}$'),
 event_category VARCHAR(36) NOT NULL CHECK(event_category IN ('RBI_POLICY','MACRO_RELEASE','OFFICIAL_INDEX_EVENT')),
 calendar_provider VARCHAR(50) NOT NULL CHECK(calendar_provider IN ('RBI_OFFICIAL_CALENDAR','NSE_OFFICIAL_CALENDAR','GOVERNMENT_RELEASE_CALENDAR')),
 scheduled_at_first_known TIMESTAMPTZ NOT NULL,
 event_start TIMESTAMPTZ NOT NULL,
 event_end TIMESTAMPTZ NOT NULL,
 original_event_schedule_sha256 CHAR(64) NOT NULL CHECK(original_event_schedule_sha256 ~ '^[a-f0-9]{64}$'),
 original_event_verified BOOLEAN NOT NULL CHECK(original_event_verified),
 calendar_rights_receipt_id UUID NOT NULL REFERENCES golden_source_rights_receipt(receipt_id) ON DELETE RESTRICT,
 index_rights_receipt_id UUID NOT NULL REFERENCES golden_source_rights_receipt(receipt_id) ON DELETE RESTRICT,
 chain_rights_receipt_id UUID NOT NULL REFERENCES golden_source_rights_receipt(receipt_id) ON DELETE RESTRICT,
 iv_rights_receipt_id UUID NOT NULL REFERENCES golden_source_rights_receipt(receipt_id) ON DELETE RESTRICT,
 normalization_rights_receipt_id UUID NOT NULL REFERENCES golden_source_rights_receipt(receipt_id) ON DELETE RESTRICT,
 pre_spot NUMERIC(20,6) NOT NULL CHECK(pre_spot>0),
 pre_iv_percent NUMERIC(12,6) NOT NULL CHECK(pre_iv_percent>0 AND pre_iv_percent<=500),
 pre_iv_tenor_days INTEGER NOT NULL CHECK(pre_iv_tenor_days=30),
 pre_iv_source_method VARCHAR(80) NOT NULL CHECK(pre_iv_source_method='LICENSED_ATM_30D_INTERPOLATION'),
 pre_exchange_at TIMESTAMPTZ NOT NULL,
 pre_first_known_at TIMESTAMPTZ NOT NULL,
 pre_index_sha256 CHAR(64) NOT NULL CHECK(pre_index_sha256 ~ '^[a-f0-9]{64}$'),
 pre_iv_sha256 CHAR(64) NOT NULL CHECK(pre_iv_sha256 ~ '^[a-f0-9]{64}$'),
 pre_normalization_sha256 CHAR(64) NOT NULL CHECK(pre_normalization_sha256 ~ '^[a-f0-9]{64}$'),
 pre_iv_original_verified BOOLEAN NOT NULL CHECK(pre_iv_original_verified),
 pre_index_original_verified BOOLEAN NOT NULL CHECK(pre_index_original_verified),
 pre_normalization_original_verified BOOLEAN NOT NULL CHECK(pre_normalization_original_verified),
 post_spot NUMERIC(20,6) NOT NULL CHECK(post_spot>0),
 post_iv_percent NUMERIC(12,6) NOT NULL CHECK(post_iv_percent>0 AND post_iv_percent<=500),
 post_iv_tenor_days INTEGER NOT NULL CHECK(post_iv_tenor_days=30),
 post_iv_source_method VARCHAR(80) NOT NULL CHECK(post_iv_source_method='LICENSED_ATM_30D_INTERPOLATION'),
 post_exchange_at TIMESTAMPTZ NOT NULL,
 post_first_known_at TIMESTAMPTZ NOT NULL,
 post_index_sha256 CHAR(64) NOT NULL CHECK(post_index_sha256 ~ '^[a-f0-9]{64}$'),
 post_iv_sha256 CHAR(64) NOT NULL CHECK(post_iv_sha256 ~ '^[a-f0-9]{64}$'),
 post_normalization_sha256 CHAR(64) NOT NULL CHECK(post_normalization_sha256 ~ '^[a-f0-9]{64}$'),
 post_iv_original_verified BOOLEAN NOT NULL CHECK(post_iv_original_verified),
 post_index_original_verified BOOLEAN NOT NULL CHECK(post_index_original_verified),
 post_normalization_original_verified BOOLEAN NOT NULL CHECK(post_normalization_original_verified),
 first_known_at TIMESTAMPTZ NOT NULL,
 captured_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 valid_until TIMESTAMPTZ NOT NULL,
 retain_until DATE NOT NULL,
 CONSTRAINT ck_vol_crush_event_time CHECK(
   scheduled_at_first_known<event_start AND event_start<event_end
   AND pre_exchange_at<event_start AND pre_exchange_at<=pre_first_known_at
   AND scheduled_at_first_known<pre_first_known_at AND pre_first_known_at<=event_start
   AND post_exchange_at>event_end AND post_exchange_at<=post_first_known_at
   AND post_first_known_at<=first_known_at
   AND first_known_at<=captured_at AND first_known_at<valid_until
   AND valid_until<=first_known_at+INTERVAL '180 seconds'),
 CONSTRAINT ck_vol_crush_distinct_quotes CHECK(
   pre_iv_sha256<>post_iv_sha256
   AND pre_index_sha256<>post_index_sha256
   AND pre_normalization_sha256<>post_normalization_sha256),
 CONSTRAINT ck_vol_crush_retention CHECK(
   retain_until>=(first_known_at AT TIME ZONE 'Asia/Kolkata')::DATE)
);
CREATE INDEX ix_fno_vol_crush_event ON fno_nifty_vol_crush_event_source
 (event_key,first_known_at DESC);

-- History source is independent completed index OHLC, not inferred
-- from option premiums or generated by a fitted backtest.
CREATE TABLE fno_nifty_vol_crush_history_source (
 evidence_id BIGSERIAL PRIMARY KEY,
 event_evidence_id BIGINT NOT NULL REFERENCES fno_nifty_vol_crush_event_source(evidence_id) ON DELETE RESTRICT,
 session_date DATE NOT NULL,
 index_open NUMERIC(20,6) NOT NULL CHECK(index_open>0),
 index_high NUMERIC(20,6) NOT NULL CHECK(index_high>0),
 index_low NUMERIC(20,6) NOT NULL CHECK(index_low>0),
 index_close NUMERIC(20,6) NOT NULL CHECK(index_close>0),
 index_exchange_close_at TIMESTAMPTZ NOT NULL,
 index_first_known_at TIMESTAMPTZ NOT NULL,
 index_source_sha256 CHAR(64) NOT NULL CHECK(index_source_sha256 ~ '^[a-f0-9]{64}$'),
 original_index_verified BOOLEAN NOT NULL CHECK(original_index_verified),
 index_rights_receipt_id UUID NOT NULL REFERENCES golden_source_rights_receipt(receipt_id) ON DELETE RESTRICT,
 first_known_at TIMESTAMPTZ NOT NULL,
 captured_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 retain_until DATE NOT NULL,
 CONSTRAINT uq_vol_crush_completed_index UNIQUE(event_evidence_id,session_date,first_known_at),
 CONSTRAINT ck_vol_crush_completed_ohlc CHECK(
   index_high>=index_open AND index_high>=index_close
   AND index_low<=index_open AND index_low<=index_close AND index_low<=index_high),
 CONSTRAINT ck_vol_crush_completed_time CHECK(
   index_exchange_close_at=(session_date::timestamp+INTERVAL '15 hours 30 minutes') AT TIME ZONE 'Asia/Kolkata'
   AND index_exchange_close_at<=index_first_known_at AND index_first_known_at<=first_known_at
   AND first_known_at<=captured_at),
 CONSTRAINT ck_vol_crush_completed_retention CHECK(
   retain_until>=(first_known_at AT TIME ZONE 'Asia/Kolkata')::DATE)
);
CREATE INDEX ix_vol_crush_event_history ON fno_nifty_vol_crush_history_source
 (event_evidence_id,session_date DESC,first_known_at DESC);

CREATE FUNCTION fno_reject_vol_crush_source_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' AND OLD.retain_until<(now() AT TIME ZONE 'Asia/Kolkata')::DATE THEN
   RETURN OLD;
 END IF;
 RAISE EXCEPTION 'Immutable original-time event anchored IV crush proof'
   USING ERRCODE='23514';
END $$;
CREATE TRIGGER tr_fno_vol_crush_event_immutable
 BEFORE UPDATE OR DELETE ON fno_nifty_vol_crush_event_source
 FOR EACH ROW EXECUTE FUNCTION fno_reject_vol_crush_source_mutation();
CREATE TRIGGER tr_fno_vol_crush_history_immutable
 BEFORE UPDATE OR DELETE ON fno_nifty_vol_crush_history_source
 FOR EACH ROW EXECUTE FUNCTION fno_reject_vol_crush_source_mutation();
