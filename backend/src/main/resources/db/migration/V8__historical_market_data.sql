-- Phase 3: bounded, resumable historical OHLCV ingestion.
-- Candle rows retain symbol/token snapshots so history remains interpretable if old catalogue rows are pruned.
CREATE TABLE market_candle (
    candle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id BIGINT NOT NULL,
    exchange VARCHAR(8) NOT NULL,
    trading_symbol VARCHAR(100) NOT NULL,
    symbol_token VARCHAR(32) NOT NULL,
    catalogue_version UUID,
    interval VARCHAR(20) NOT NULL CHECK (interval IN (
        'ONE_MINUTE','THREE_MINUTE','FIVE_MINUTE','TEN_MINUTE',
        'FIFTEEN_MINUTE','THIRTY_MINUTE','ONE_HOUR','ONE_DAY'
    )),
    candle_time TIMESTAMPTZ NOT NULL,
    open_price NUMERIC(20,6) NOT NULL CHECK (open_price > 0),
    high_price NUMERIC(20,6) NOT NULL CHECK (high_price > 0),
    low_price NUMERIC(20,6) NOT NULL CHECK (low_price > 0),
    close_price NUMERIC(20,6) NOT NULL CHECK (close_price > 0),
    volume BIGINT NOT NULL CHECK (volume >= 0),
    source VARCHAR(40) NOT NULL DEFAULT 'ANGEL_ONE_SMARTAPI',
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_market_candle_ohlc CHECK (
        high_price >= low_price
        AND high_price >= open_price AND high_price >= close_price
        AND low_price <= open_price AND low_price <= close_price
    ),
    CONSTRAINT uq_market_candle_identity UNIQUE (exchange, symbol_token, interval, candle_time)
);
CREATE INDEX ix_market_candle_lookup
    ON market_candle (exchange, symbol_token, interval, candle_time DESC);
CREATE INDEX ix_market_candle_symbol_lookup
    ON market_candle (exchange, trading_symbol, interval, candle_time DESC);

CREATE TABLE candle_backfill_run (
    id UUID PRIMARY KEY,
    instrument_id BIGINT NOT NULL,
    exchange VARCHAR(8) NOT NULL,
    trading_symbol VARCHAR(100) NOT NULL,
    symbol_token VARCHAR(32) NOT NULL,
    catalogue_version UUID,
    interval VARCHAR(20) NOT NULL CHECK (interval IN (
        'ONE_MINUTE','THREE_MINUTE','FIVE_MINUTE','TEN_MINUTE',
        'FIFTEEN_MINUTE','THIRTY_MINUTE','ONE_HOUR','ONE_DAY'
    )),
    from_date DATE NOT NULL,
    to_date DATE NOT NULL,
    next_from_date DATE NOT NULL,
    status VARCHAR(12) NOT NULL CHECK (status IN ('RUNNING','PARTIAL','SUCCEEDED','FAILED')),
    chunks_completed INTEGER NOT NULL DEFAULT 0 CHECK (chunks_completed >= 0),
    fetched_rows BIGINT NOT NULL DEFAULT 0 CHECK (fetched_rows >= 0),
    persisted_rows BIGINT NOT NULL DEFAULT 0 CHECK (persisted_rows >= 0),
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    error_code VARCHAR(80),
    error_message VARCHAR(500),
    CONSTRAINT ck_candle_backfill_date_range CHECK (from_date <= to_date)
);
CREATE INDEX ix_candle_backfill_recent ON candle_backfill_run (started_at DESC);
CREATE INDEX ix_candle_backfill_status ON candle_backfill_run (status, updated_at DESC);

CREATE TABLE candle_backfill_checkpoint (
    checkpoint_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL REFERENCES candle_backfill_run(id) ON DELETE CASCADE,
    chunk_from_date DATE NOT NULL,
    chunk_to_date DATE NOT NULL,
    status VARCHAR(12) NOT NULL CHECK (status IN ('SUCCEEDED','FAILED')),
    fetched_rows INTEGER NOT NULL DEFAULT 0 CHECK (fetched_rows >= 0),
    persisted_rows INTEGER NOT NULL DEFAULT 0 CHECK (persisted_rows >= 0),
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    error_code VARCHAR(80),
    error_message VARCHAR(500),
    CONSTRAINT ck_candle_checkpoint_date_range CHECK (chunk_from_date <= chunk_to_date)
);
CREATE INDEX ix_candle_checkpoint_run ON candle_backfill_checkpoint (run_id, checkpoint_id);
